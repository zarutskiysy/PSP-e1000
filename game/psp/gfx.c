uint32_t bw_scale_color(uint32_t c, int num, int den) {
    uint32_t r = c & 0xFF, gg = (c >> 8) & 0xFF, b = (c >> 16) & 0xFF;
    if (num < 0) num = 0;
    if (num > den) num = den;
    r = r * (uint32_t)num / (uint32_t)den;
    gg = gg * (uint32_t)num / (uint32_t)den;
    b = b * (uint32_t)num / (uint32_t)den;
    return BW_RGB(r, gg, b);
}

void bw_clear(bw_gfx_t *g, uint32_t c) {
    int i, n = BW_STRIDE * BW_SCREEN_H;
    for (i = 0; i < n; i++) g->px[i] = c;
}

void bw_pixel(bw_gfx_t *g, int x, int y, uint32_t c) {
    if ((unsigned)x < BW_SCREEN_W && (unsigned)y < BW_SCREEN_H) g->px[y * BW_STRIDE + x] = c;
}

void bw_fill_rect(bw_gfx_t *g, int x, int y, int w, int h, uint32_t c) {
    int i, j;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > BW_SCREEN_W) w = BW_SCREEN_W - x;
    if (y + h > BW_SCREEN_H) h = BW_SCREEN_H - y;
    for (j = 0; j < h; j++) {
        uint32_t *row = g->px + (y + j) * BW_STRIDE + x;
        for (i = 0; i < w; i++) row[i] = c;
    }
}

void bw_rect(bw_gfx_t *g, int x, int y, int w, int h, uint32_t c) {
    bw_fill_rect(g, x, y, w, 1, c);
    bw_fill_rect(g, x, y + h - 1, w, 1, c);
    bw_fill_rect(g, x, y, 1, h, c);
    bw_fill_rect(g, x + w - 1, y, 1, h, c);
}

void bw_line(bw_gfx_t *g, int x0, int y0, int x1, int y1, uint32_t c) {
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1;
    int dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1;
    int err = dx + dy, n = 0;
    for (;;) {
        bw_pixel(g, x0, y0, c);
        if ((x0 == x1 && y0 == y1) || ++n > 4096) break;
        {
            int e2 = 2 * err;
            if (e2 >= dy) { err += dy; x0 += sx; }
            if (e2 <= dx) { err += dx; y0 += sy; }
        }
    }
}

void bw_circle(bw_gfx_t *g, int cx, int cy, int r, uint32_t c) {
    int x = r, y = 0, err = 1 - r;
    while (x >= y) {
        bw_pixel(g, cx + x, cy + y, c); bw_pixel(g, cx - x, cy + y, c);
        bw_pixel(g, cx + x, cy - y, c); bw_pixel(g, cx - x, cy - y, c);
        bw_pixel(g, cx + y, cy + x, c); bw_pixel(g, cx - y, cy + x, c);
        bw_pixel(g, cx + y, cy - x, c); bw_pixel(g, cx - y, cy - x, c);
        y++;
        if (err < 0) err += 2 * y + 1;
        else { x--; err += 2 * (y - x) + 1; }
    }
}

void bw_fill_circle(bw_gfx_t *g, int cx, int cy, int r, uint32_t c) {
    int y;
    for (y = -r; y <= r; y++) {
        int x = 0;
        while ((x + 1) * (x + 1) + y * y <= r * r) x++;
        bw_fill_rect(g, cx - x, cy + y, 2 * x + 1, 1, c);
    }
}

int bw_text(bw_gfx_t *g, int x, int y, const char *s, uint32_t c, int scale) {
    if (scale < 1) scale = 1;
    for (; *s; s++) {
        int ch = (unsigned char)*s, col, row;
        if (ch == '\n') { y += 8 * scale; continue; }
        if (ch >= 'a' && ch <= 'z') ch -= 32;
        if (ch < 0x20 || ch > 0x5F) ch = '?';
        for (col = 0; col < 5; col++) {
            uint8_t bits = font5x7[ch - 0x20][col];
            for (row = 0; row < 7; row++)
                if (bits & (1u << row)) bw_fill_rect(g, x + col * scale, y + row * scale, scale, scale, c);
        }
        x += 6 * scale;
    }
    return x;
}
