#!/usr/bin/env python3
"""Generates companion/psp/font_data.h: anti-aliased ASCII bitmaps of Aileron Regular at three sizes.

Aileron (Sora Sagano, dotcolon.net) is CC0 and ships inside Pillow as ImageFont.load_default(size).
Regenerate: python companion/tools/gen_font.py
"""
from __future__ import annotations

import pathlib

from PIL import ImageFont

SIZES = {"small": 11, "body": 14, "title": 18}
TRACKING = {"small": 0.45, "body": 0.2, "title": 0.0}  # extra advance: tiny sizes need air after hinting
FIRST, LAST = 32, 126
OUT = pathlib.Path(__file__).resolve().parents[1] / "psp" / "font_data.h"


def build(name: str, size: int) -> tuple[str, int]:
    font = ImageFont.load_default(size=size)
    ascent, descent = font.getmetrics()
    data: list[int] = []
    rows = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        adv = round(font.getlength(ch) + TRACKING[name])
        if ch == " ":
            adv = max(adv, round(size * 0.32))
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            mask = font.getmask(ch, mode="L", anchor="ls")
            mw, mh = mask.size
            for y in range(h):
                for x in range(w):
                    data.append(mask.getpixel((x, y)) if x < mw and y < mh else 0)
        rows.append(f"{{{off},{w},{h},{l},{t + ascent},{adv}}}")
    text = [f"static const unsigned char font_{name}_data[{len(data) or 1}] = {{"]
    for i in range(0, len(data), 32):
        text.append(",".join(map(str, data[i : i + 32])) + ",")
    text.append("};")
    text.append(f"static const font_glyph_t font_{name}_glyphs[{LAST - FIRST + 1}] = {{")
    for i in range(0, len(rows), 6):
        text.append(",".join(rows[i : i + 6]) + ",")
    text.append("};")
    text.append(f"static const font_t font_{name} = {{font_{name}_glyphs, font_{name}_data, {ascent + descent}, {ascent}}};")
    return "\n".join(text), len(data)


def main() -> None:
    parts = [
        "/* GENERATED by companion/tools/gen_font.py. Do not edit.",
        " * Aileron Regular (Sora Sagano, https://dotcolon.net/fonts/aileron), CC0 1.0, as bundled in Pillow. */",
        "#ifndef FONT_DATA_H",
        "#define FONT_DATA_H",
        '#include "gfx.h"',
    ]
    total = 0
    for name, size in SIZES.items():
        block, n = build(name, size)
        parts.append(block)
        total += n
    parts.append("#endif")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"{OUT}: {total} bytes of glyph data")


if __name__ == "__main__":
    main()
